"""Rewrite tests/slow_tests.txt from a timed run, so the unit tier stays fast.

    scripts/test.sh full --junitxml=/tmp/t.xml
    python scripts/update_slow_tests.py /tmp/t.xml

A test slower than --seconds is listed by file and test name, parameters collapsed, so
a parametrized test is slow as a whole. tests/conftest.py marks the listed tests `slow`.
"""
import argparse
import re
import xml.etree.ElementTree as ET
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "tests" / "slow_tests.txt"


def key(case):
    """'tests/a/test_b.py::TestC::test_d', without parameters."""
    parts = case.get("classname").split(".")
    i = next(n for n, p in enumerate(parts) if p.startswith("test_"))
    path = "/".join(parts[: i + 1]) + ".py"
    return "::".join([path, *parts[i + 1:], re.sub(r"\[.*$", "", case.get("name"))])


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("junit_xml")
    ap.add_argument("--seconds", type=float, default=5.0)
    a = ap.parse_args()
    slow = {}
    for case in ET.parse(a.junit_xml).getroot().iter("testcase"):
        if float(case.get("time", 0)) >= a.seconds:
            k = key(case)
            slow[k] = max(slow.get(k, 0.0), float(case.get("time")))
    head = ["# Tests slower than %g s, marked `slow` by tests/conftest.py." % a.seconds,
            "# Generated by scripts/update_slow_tests.py; do not edit by hand."]
    OUT.write_text("\n".join(head + sorted(slow)) + "\n")
    print(f"{OUT}: {len(slow)} tests, {sum(slow.values()):.0f} s at their slowest parameter")


if __name__ == "__main__":
    main()
